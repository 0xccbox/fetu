/// Код ошибки загрузки подписки (для локализации в UI).
///
/// Контроллер мапит исключения парсера и сети в код; UI переводит
/// код в сообщение через `AppLocalizations` (AGENTS.md, правило 14).
enum SubscriptionError {
  /// Пустой URL подписки.
  enterUrl,

  /// URL обновления не задан.
  noUpdateUrl,

  /// Сеть недоступна / сервер не ответил.
  network,

  /// Загрузка не удалось.
  loadFailed,

  /// Сохранённая запись повреждена.
  broken,

  /// Не удалось сохранить подписку.
  saveFailed,

  /// Ключи vpn:// не настроены.
  noKeys,

  /// Ключ подписки некорректен.
  invalidKey,

  /// Подписка истекла.
  expired,

  /// Устаревшая версия формата.
  outdatedVersion,

  /// Нет доступных серверов.
  noNodes,

  /// У узла нет TCP-канала.
  noTcpChannel,

  /// Подпись невалидна.
  signature,

  /// Прочая структурная ошибка подписки.
  invalid,
}
