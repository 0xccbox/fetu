/// Код ошибки операции подключения (для локализации в UI).
///
/// Контроллер выставляет код; UI переводит его в сообщение
/// через `AppLocalizations` (AGENTS.md, правило 14). Сырой текст
/// остаётся только в debug-логах.
enum ConnectionError {
  /// Узел подключения не указан.
  nodeMissing,

  /// Подключение не удалось.
  connectFailed,

  /// В сборке отсутствует нативное ядро VPN.
  coreUnavailable,

  /// Отключение не удалось.
  disconnectFailed,
}
